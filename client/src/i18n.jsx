const STORAGE_KEY = 'wander_lang';
const I18nContext = createContext(null);

function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = typeof localStorage !== 'undefined' && localStorage.getItem(STORAGE_KEY);
    return saved && T[saved] ? saved : 'en';
  });

  useEffect(() => {
    const info = LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0];
    document.documentElement.lang = lang;
    document.documentElement.dir = info.dir;
  }, [lang]);

  const setLang = (code) => {
    if (!T[code]) return;
    localStorage.setItem(STORAGE_KEY, code);
    setLangState(code);
  };

  const value = useMemo(() => {
    const dict = T[lang] || T.en;
    const t = (key, vars) => interpolate(dict[key] ?? T.en[key] ?? key, vars);
    return { lang, setLang, t, languages: LANGUAGES };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
