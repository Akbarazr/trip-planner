export function templatePlacesForDays(template, days) {
  const count = Math.max(1, Math.min(7, Number(days) || 1));
  const placeCount = Math.min(template.places.length, count + 2);
  return template.places.slice(0, placeCount);
}

export function buildTemplateItinerary(template, days, startDate) {
  const dayCount = Math.max(1, Math.min(7, Number(days) || 1));
  const places = templatePlacesForDays(template, dayCount);
  const itinerary = Array.from({ length: dayCount }, (_, index) => {
    let date = null;
    if (startDate) {
      const value = new Date(`${startDate}T12:00:00`);
      value.setDate(value.getDate() + index);
      date = value.toISOString().slice(0, 10);
    }
    return { date, stops: [] };
  });
  places.forEach((name, index) => {
    itinerary[index % dayCount].stops.push({ name });
  });
  return itinerary;
}
